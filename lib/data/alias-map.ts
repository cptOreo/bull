export function resolveSymbol(input: string): string {
  const clean = input.trim().toLowerCase();
  if (INDIAN_STOCK_ALIASES[clean]) return INDIAN_STOCK_ALIASES[clean];
  if (US_STOCK_ALIASES[clean]) return US_STOCK_ALIASES[clean];

  const upper = input.trim().toUpperCase();
  if (upper.includes(".")) return upper;
  if (/^[A-Z]{1,5}$/.test(upper)) return `${upper}.NS`;
  return upper;
}